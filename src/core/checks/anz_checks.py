class ANZ2Checker(BaseChecker):
    def __init__(self):
        super().__init__("АНЗ.2", "Контроль установки обновлений программного обеспечения", "high", is_manual=False)
        self.required_levels = [1, 2, 3, 4]
        self.detailed_description = r"""
📌 ЧТО ПРОВЕРЯЕТСЯ:
Проверяется, включены ли автоматические обновления Windows и как давно устанавливались обновления.

✅ ПОЧЕМУ ЭТО ВАЖНО:
- Неустановленные обновления содержат исправления известных уязвимостей
- Злоумышленники активно эксплуатируют старые уязвимости
- Регулярные обновления — основа безопасности

📋 НОРМАТИВНОЕ ТРЕБОВАНИЕ (Приказ ФСТЭК №21 п. VIII, мера 2):
Должен осуществляться контроль установки обновлений операционной системы и прикладного программного обеспечения.

🛠️ КАК НАСТРОИТЬ:

1. Включите автоматические обновления Windows:
   - Настройки → Обновление и безопасность → Центр обновления Windows
   - Выберите 'Автоматически устанавливать обновления'

2. Настройте политику обновлений через gpedit.msc:
   - Конфигурация компьютера → Административные шаблоны → Компоненты Windows → Центр обновления Windows
   - Включите 'Настроить автоматическое обновление'

3. Для прикладного ПО используйте централизованные системы обновлений (WSUS, SCCM)

📊 ДОПОЛНИТЕЛЬНЫЕ РЕКОМЕНДАЦИИ:
- Для УЗ-1 и УЗ-2 — обязательный контроль обновлений
- Установите политику 'Автоматическая установка критических обновлений в течение 7 дней'
- Регулярно проверяйте статус обновлений
"""
    
    def check(self) -> dict:
        auto, days = get_windows_update_status()
        issues = []
        
        if not auto:
            issues.append("- Автоматические обновления не включены.")
        
        if days == -1:
            issues.append("- Не удалось определить дату последнего обновления.")
        elif days > 30:
            issues.append(f"- Последнее обновление было {days} дней назад (рекомендуется не более 30).")
        
        if issues:
            return self._get_result(False, "\n".join(issues), "❌ " + "; ".join(issues).replace("-", ""))
        else:
            return self._get_result(True, f"Автообновление включено, последнее обновление {days} дн. назад", "✅ Обновления контролируются.")


