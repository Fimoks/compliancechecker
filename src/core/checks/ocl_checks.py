# ОЦЛ.4 — ЗАЩИТА ОТ СПАМА
# ============================================================================

class OCL4Checker(BaseChecker):
    def __init__(self):
        super().__init__("ОЦЛ.4", "Защита от спама", "medium", is_manual=False)
        self.required_levels = [1, 2]
        self.detailed_description = r"""
📌 ЧТО ПРОВЕРЯЕТСЯ:
Проверяется, настроена ли защита от спама (почтовых рассылок, фишинговых писем).

✅ ПОЧЕМУ ЭТО ВАЖНО:
- Спам часто содержит фишинговые ссылки и вредоносные вложения
- Массовые рассылки отвлекают сотрудников и снижают продуктивность
- Обязательное требование для УЗ-1 и УЗ-2

📋 НОРМАТИВНОЕ ТРЕБОВАНИЕ (Приказ ФСТЭК №21 п. IX, мера 4):
Должен осуществляться контроль содержания информации, передаваемой из информационной системы, включая защиту от спама.

🛠️ КАК НАСТРОИТЬ:

Для корпоративной почты (Exchange/Office 365):
1. Включите фильтрацию спама в Exchange Online Protection (EOP)
2. Настройте политики защиты от спама и фишинга
3. Установите уровень Block для заведомо опасных доменов

Для почтовых клиентов (Outlook):
1. Настройте фильтр нежелательной почты
2. Установите уровень защиты 'Высокий'
3. Настройте блокировку внешних изображений

Сторонние решения:
- Kaspersky Anti-Spam
- Dr.Web Anti-Spam
- Mailcleaner (Open Source)

📊 ДОПОЛНИТЕЛЬНЫЕ РЕКОМЕНДАЦИИ:
- Регулярно обновляйте списки спам-адресов
- Настройте карантин для подозрительных писем
- Обучайте сотрудников распознавать фишинг
"""
    
    def check(self) -> dict:
        if is_antispam_configured():
            return self._get_result(True, "Антиспам-защита настроена", "✅ Защита от спама активна.")
        else:
            return self._get_result(False, "Антиспам-защита не настроена", "⚠️ Антиспам-защита не настроена. Рекомендуется настроить фильтрацию спама в почтовом клиенте или на сервере.")


