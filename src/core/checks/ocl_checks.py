# ОЦЛ.1 — КОНТРОЛЬ ЦЕЛОСТНОСТИ ПРОГРАММНОГО ОБЕСПЕЧЕНИЯ
# ============================================================================

class OCL1Checker(BaseChecker):
    def __init__(self):
        super().__init__("ОЦЛ.1", "Контроль целостности программного обеспечения", "high", is_manual=False)
        self.required_levels = [1, 2]
        self.detailed_description = r"""
📌 ЧТО ПРОВЕРЯЕТСЯ:
Проверяется, настроен ли контроль целостности программного обеспечения (AppLocker или SRP).

✅ ПОЧЕМУ ЭТО ВАЖНО:
- Предотвращает запуск вредоносного и неразрешённого ПО
- Контролирует изменения в системных файлах
- Обязательное требование для УЗ-1 и УЗ-2

📋 НОРМАТИВНОЕ ТРЕБОВАНИЕ (Приказ ФСТЭК №21 п. IX, мера 1):
Должен осуществляться контроль целостности программного обеспечения и персональных данных.

🛠️ КАК НАСТРОИТЬ AppLocker:

1. Запустите службу Application Identity:
   - Нажмите Win+R, введите services.msc
   - Найдите 'Application Identity'
   - Установите тип запуска 'Автоматически' и запустите службу

2. Настройте правила AppLocker:
   - Нажмите Win+R, введите secpol.msc
   - Перейдите: Политики управления приложениями → AppLocker
   - Создайте правила для 'Исполняемые файлы'
   - Добавьте разрешённые пути: C:\Program Files\*, C:\Windows\*

3. Включите правила:
   - Нажмите 'Настроить применение правил'
   - Включите правила для всех типов

ИЛИ используйте SRP (Software Restriction Policies):
- gpedit.msc → Конфигурация компьютера → Windows → Параметры безопасности → Политики ограничения ПО

📊 ДОПОЛНИТЕЛЬНЫЕ РЕКОМЕНДАЦИИ:
- Регулярно обновляйте список разрешённых приложений
- Включите аудит нарушений AppLocker
- Используйте сертификаты для подписи разрешённого ПО
"""
    
    def check(self) -> dict:
        if is_integrity_control_configured():
            return self._get_result(True, "Контроль целостности настроен", "✅ AppLocker или SRP активны. Контроль целостности ПО осуществляется.")
        else:
            return self._get_result(False, "Контроль целостности не настроен", "❌ Контроль целостности ПО не настроен. Настройте AppLocker через secpol.msc или SRP через gpedit.msc.")


