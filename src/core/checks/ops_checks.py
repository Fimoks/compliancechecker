# ОПС.3 — УСТАНОВКА ТОЛЬКО РАЗРЕШЁННОГО ПРОГРАММНОГО ОБЕСПЕЧЕНИЯ
# ============================================================================

class OPS3Checker(BaseChecker):
    def __init__(self):
        super().__init__("ОПС.3", "Установка только разрешённого программного обеспечения", "critical", is_manual=False)
        self.required_levels = [1]
        self.detailed_description = r"""
📌 ЧТО ПРОВЕРЯЕТСЯ:
Проверяется, настроен ли AppLocker или аналогичное средство ограничения запуска приложений.

✅ ПОЧЕМУ ЭТО ВАЖНО:
- Запрещает запуск неразрешённых приложений, включая вредоносные
- Предотвращает выполнение скриптов и установщиков из ненадёжных источников
- Является обязательным требованием для УЗ-1 (максимальный уровень защищённости)

📋 НОРМАТИВНОЕ ТРЕБОВАНИЕ (Приказ ФСТЭК №21 п. III, мера 3):
Должно быть реализовано ограничение программной среды — запуск только разрешённого программного обеспечения.

🛠️ КАК НАСТРОИТЬ AppLocker:

1. Запустите службу Application Identity:
   - Нажмите Win+R, введите services.msc
   - Найдите 'Application Identity'
   - Установите тип запуска 'Автоматически' и запустите службу

2. Настройте правила AppLocker:
   - Нажмите Win+R, введите secpol.msc
   - Перейдите: Политики управления приложениями → AppLocker
   - Создайте правила для 'Исполняемые файлы', 'Скрипты', 'Установщики Windows'
   - Добавьте разрешённые приложения (например, C:\Program Files\* разрешить)

3. Включите правила:
   - Нажмите 'Настроить применение правил' в правой панели
   - Включите правила для всех типов

ИЛИ через PowerShell (от администратора):
# Включить службу Application Identity
Set-Service -Name AppIDSvc -StartupType Automatic
Start-Service -Name AppIDSvc

# Создать правило разрешения для Program Files
$Rule = New-AppLockerPolicy -RuleType Exe -User Everyone -Path "C:\Program Files\*" -Action Allow
Set-AppLockerPolicy -Policy $Rule

📊 ДОПОЛНИТЕЛЬНЫЕ РЕКОМЕНДАЦИИ:
- Для УЗ-1 использование AppLocker или SRP обязательно
- Настройте отдельные правила для разных групп пользователей
- Включите аудит нарушений AppLocker
- Регулярно обновляйте список разрешённых приложений
"""
    
    def check(self) -> dict:
        if is_applocker_enabled():
            return self._get_result(
                True,
                "AppLocker настроен",
                "✅ Программное обеспечение ограничено разрешённым списком."
            )
        else:
            return self._get_result(
                False,
                "AppLocker не настроен",
                "❌ AppLocker не настроен. Для УЗ-1 обязательно настройте AppLocker или SRP через secpol.msc."
            )


