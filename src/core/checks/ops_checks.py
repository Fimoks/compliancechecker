# ОПС.2 — УПРАВЛЕНИЕ УСТАНОВКОЙ ПРОГРАММНОГО ОБЕСПЕЧЕНИЯ
# ============================================================================

class OPS2Checker(BaseChecker):
    def __init__(self):
        super().__init__("ОПС.2", "Управление установкой программного обеспечения", "high", is_manual=False)
        self.required_levels = [1, 2]
        self.detailed_description = r"""
📌 ЧТО ПРОВЕРЯЕТСЯ:
Проверяется, имеет ли текущий пользователь права администратора, позволяющие устанавливать программное обеспечение.

✅ ПОЧЕМУ ЭТО ВАЖНО:
- Несанкционированная установка ПО — одна из основных причин заражения вредоносным ПО
- Пользователи могут устанавливать нелицензионное или небезопасное ПО
- Каждое установленное приложение увеличивает поверхность атаки

📋 НОРМАТИВНОЕ ТРЕБОВАНИЕ (Приказ ФСТЭК №21 п. III, мера 2):
Установка компонентов программного обеспечения должна ограничиваться для обычных пользователей, разрешена только администраторам.

🛠️ КАК ИСПРАВИТЬ:
1. Создайте отдельную учётную запись для повседневной работы без прав администратора:
   - Настройки → Учётные записи → Семья и другие пользователи
   - Добавьте пользователя с типом 'Обычный пользователь'

2. Используйте учётную запись администратора только для:
   - Установки ПО
   - Изменения системных настроек
   - Администрирования

3. Включите контроль учётных записей (UAC) на максимальный уровень

📊 ДОПОЛНИТЕЛЬНЫЕ РЕКОМЕНДАЦИИ:
- Используйте политику 'Запуск от имени администратора' только при необходимости
- Настройте инвентаризацию установленного ПО
- Регулярно проверяйте список установленных программ
- Внедрите систему управления обновлениями (WSUS)
"""
    
    def check(self) -> dict:
        if is_user_admin():
            return self._get_result(
                False,
                "Текущий пользователь - администратор",
                "❌ Пользователь может устанавливать ПО. Создайте обычную учётную запись для повседневной работы."
            )
        else:
            return self._get_result(
                True,
                "Ограниченные права",
                "✅ Пользователь не имеет прав администратора, установка ПО невозможна."
            )


