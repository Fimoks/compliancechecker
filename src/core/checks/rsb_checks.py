        if is_audit_logon_enabled():
            return self._get_result(True, "Включён", "✅ Аудит входа в систему включён (успешные и неудачные попытки).")
        else:
            return self._get_result(False, "Не включён", "❌ Аудит входа в систему не включён. Настройте через gpedit.msc или auditpol.")


