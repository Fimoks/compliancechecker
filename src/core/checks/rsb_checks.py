# РСБ.3 — СБОР, ЗАПИСЬ И ХРАНЕНИЕ СОБЫТИЙ БЕЗОПАСНОСТИ
# ============================================================================

class RSB3Checker(BaseChecker):
    def __init__(self):
        super().__init__("РСБ.3", "Сбор, запись и хранение событий безопасности", "high", is_manual=False)
        self.required_levels = [1, 2, 3, 4]
        self.detailed_description = r"""
📌 ЧТО ПРОВЕРЯЕТСЯ:
Проверяются параметры журнала событий Security: размер и срок хранения.

✅ ПОЧЕМУ ЭТО ВАЖНО:
- Недостаточный размер журнала приводит к потере событий
- Слишком короткий срок хранения затрудняет расследование
- Журналы должны храниться не менее года

📋 НОРМАТИВНОЕ ТРЕБОВАНИЕ (Приказ ФСТЭК №21 п. V, мера 3):
Должен осуществляться сбор, запись и хранение информации о событиях безопасности.

🛠️ КАК НАСТРОИТЬ:

1. Откройте Event Viewer (eventvwr.msc)
2. Перейдите в 'Журналы Windows' → 'Безопасность'
3. Нажмите 'Свойства' (правой кнопкой)
4. Установите:
   - Максимальный размер журнала: 262144 КБ (256 МБ) или больше
   - При достижении максимального размера: 'Архивировать журнал при заполнении'
5. Настройте 'Сохранять события' на 365 дней

ИЛИ через PowerShell (от администратора):
$log = Get-WmiObject -Class Win32_NTEventlogFile -Filter "LogFileName='Security'"
$log.MaxFileSize = 262144
$log.Put()

📊 ДОПОЛНИТЕЛЬНЫЕ РЕКОМЕНДАЦИИ:
- Храните журналы не менее 1 года
- Настройте экспорт журналов в SIEM-систему
- Регулярно архивируйте журналы
"""
    
    def check(self) -> dict:
        max_size = get_event_log_max_size()
        retention_days = get_event_log_retention_days()
        issues = []
        details = []
        
        if max_size < 100:
            issues.append(f"- Размер журнала Security: {max_size} МБ (рекомендуется ≥100 МБ).")
        else:
            details.append(f"Размер: {max_size} МБ")
            
        if retention_days == 0:
            issues.append("- Срок хранения событий не задан (может привести к переполнению).")
        elif retention_days < 365:
            issues.append(f"- Срок хранения событий: {retention_days} дней (рекомендуется ≥365).")
        else:
            details.append(f"хранение: {retention_days} дн.")
        
        if issues:
            return self._get_result(False, "\n".join(issues), "❌ " + "; ".join(issues).replace("-", ""))
        else:
            return self._get_result(True, ", ".join(details), "✅ Сбор и хранение событий настроены корректно.")


