# ============================================================================
# УКФ.1 — ОПРЕДЕЛЕНИЕ ЛИЦ, РАЗРЕШЁННЫХ НА ИЗМЕНЕНИЯ
# ============================================================================

class UKF1ManualChecker(BaseChecker):
    def __init__(self):
        super().__init__("УКФ.1", "Определение лиц, разрешённых на изменения конфигурации", "high", is_manual=True)
        self.required_levels = [1, 2, 3]
        self.question = ("Определён ли перечень лиц (сотрудников), которым разрешено вносить изменения в конфигурацию "
                         "информационной системы и системы защиты персональных данных?")
        self.detailed_description = r"""
📌 ЧТО ПРОВЕРЯЕТСЯ:
Ручная проверка — наличие утверждённого списка лиц, имеющих право вносить изменения в конфигурацию.

✅ ПОЧЕМУ ЭТО ВАЖНО:
- Изменения конфигурации могут повлиять на безопасность
- Несанкционированные изменения — частая причина инцидентов
- Обязательное требование для УЗ-1,2,3

📋 НОРМАТИВНОЕ ТРЕБОВАНИЕ (Приказ ФСТЭК №21 п. XV, мера 1):
Должны быть определены лица, которым разрешено вносить изменения в конфигурацию.

🛠️ КАК ОРГАНИЗОВАТЬ:
1. Сформируйте перечень сотрудников, имеющих право на внесение изменений:
   - Администраторы ИС
   - Администраторы СЗИ
   - Разработчики (при необходимости)

2. Утвердите перечень приказом руководителя

3. Разграничьте права в соответствии с ролями:
   - Право на изменение только у конкретных учётных записей
   - Право на утверждение — у руководителя

4. Регулярно (раз в квартал) актуализируйте перечень

📊 ДОПОЛНИТЕЛЬНЫЕ РЕКОМЕНДАЦИИ:
- Используйте системы учёта доступа (Identity Management)
- Внедрите двухфакторную авторизацию для критических изменений
- Ведите журнал выдачи прав на изменения
"""
    
    def check(self) -> dict:
        return self._get_result(False, None, self.question)


