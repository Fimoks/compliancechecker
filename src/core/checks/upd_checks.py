# УПД.1 — УПРАВЛЕНИЕ УЧЕТНЫМИ ЗАПИСЯМИ ПОЛЬЗОВАТЕЛЕЙ
# ============================================================================

class UPD1Checker(BaseChecker):
    def __init__(self):
        super().__init__("УПД.1", "Управление учетными записями пользователей", "high", is_manual=False)
        self.required_levels = [1, 2, 3, 4]
        self.detailed_description = r"""
📌 ЧТО ПРОВЕРЯЕТСЯ:
Проверяется наличие активной гостевой учётной записи и общее количество локальных пользователей.

✅ ПОЧЕМУ ЭТО ВАЖНО:
- Гостевая учётная запись даёт неавторизованный доступ к системе без аутентификации
- Каждая лишняя учётная запись увеличивает поверхность атаки
- Неиспользуемые учётные записи могут быть скомпрометированы

📋 НОРМАТИВНОЕ ТРЕБОВАНИЕ (Приказ ФСТЭК №21 п. II, мера 1):
Должно осуществляться управление учётными записями пользователей, включая создание, блокирование и удаление. Неиспользуемые учётные записи должны блокироваться.

🛠️ КАК ИСПРАВИТЬ:
1. Отключите гостевую учётную запись:
   - Откройте lusrmgr.msc
   - Перейдите в "Пользователи"
   - Дважды кликните по "Гость"
   - Поставьте галочку "Отключить учётную запись"

2. Удалите неиспользуемые учётные записи:
   - Просмотрите список пользователей в lusrmgr.msc
   - Удалите учётные записи, которые больше не нужны

📊 ДОПОЛНИТЕЛЬНЫЕ РЕКОМЕНДАЦИИ:
- Регулярно проводите аудит учётных записей (раз в месяц)
- Ведите журнал создания и удаления учётных записей
- Используйте политику "минимально необходимых привилегий"
"""
    
    def check(self) -> dict:
        users = get_local_users()
        guest_status = get_registry_value(
            r"SOFTWARE\Microsoft\Windows NT\CurrentVersion\Winlogon\SpecialAccounts\UserList",
            "Guest"
        )
        guest_disabled = (guest_status == 0 or guest_status is None)
        
        if not guest_disabled:
            return self._get_result(False, users, "❌ Гостевая учётная запись активна. Отключите Guest через lusrmgr.msc")
        return self._get_result(True, users, f"✅ Учётных записей: {len(users)}, гостевая отключена")


