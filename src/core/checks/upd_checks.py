class UPD13Checker(BaseChecker):
    def __init__(self):
        super().__init__("УПД.13", "Защищенный удаленный доступ", "high", is_manual=False)
        self.required_levels = [1, 2, 3, 4]
        self.detailed_description = r"""
📌 ЧТО ПРОВЕРЯЕТСЯ:
Проверяется состояние удалённого доступа через RDP.

✅ ПОЧЕМУ ЭТО ВАЖНО:
- RDP — частая цель атак
- Неправильные настройки могут привести к взлому
- Требуется дополнительная защита при использовании

📋 НОРМАТИВНОЕ ТРЕБОВАНИЕ (Приказ ФСТЭК №21 п. II, мера 13):
Должна быть реализована защита удалённого доступа с использованием защищённых протоколов (RDP с шифрованием, VPN).

🛠️ КАК НАСТРОИТЬ:

Если RDP не нужен (рекомендуется):
1. Откройте 'Система' → 'Удалённый рабочий стол'
2. Выключите 'Удалённый рабочий стол'

Если RDP нужен:
1. Включите шифрование TLS:
   - gpedit.msc → Административные шаблоны → Компоненты Windows → Службы удалённых рабочих столов
   - Включите 'Требовать использование специального уровня безопасности' (TLS 1.2)

2. Используйте VPN для удалённого доступа
3. Измените стандартный порт 3389

📊 ДОПОЛНИТЕЛЬНЫЕ РЕКОМЕНДАЦИИ:
- Используйте многофакторную аутентификацию
- Ограничьте список пользователей для удалённого доступа
- Включите аудит входа через RDP
"""
    
    def check(self) -> dict:
        try:
            result = subprocess.run(
                ['reg', 'query', 'HKLM\\SYSTEM\\CurrentControlSet\\Control\\Terminal Server', '/v', 'fDenyTSConnections'],
                capture_output=True, text=True, encoding='cp866', errors='replace'
            )
            if '0x0' in result.stdout:
                return self._get_result(False, "RDP включён", 
                    "⚠️ RDP доступен. Убедитесь, что используется VPN и шифрование TLS. Рекомендуется отключить RDP, если не нужен")
            else:
                return self._get_result(True, "RDP отключён", "✅ Удалённый доступ через RDP отключён")
        except:
            return self._get_result(True, "OK", "✅ Не удалось проверить RDP, но рекомендуется использовать VPN")


