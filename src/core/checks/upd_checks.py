class UPD14Checker(BaseChecker):
    def __init__(self):
        super().__init__("УПД.14", "Контроль беспроводного доступа", "medium", is_manual=False)
        self.required_levels = [1, 2, 3, 4]
        self.detailed_description = r"""
📌 ЧТО ПРОВЕРЯЕТСЯ:
Проверяется состояние беспроводных сетей и используемые протоколы шифрования.

✅ ПОЧЕМУ ЭТО ВАЖНО:
- Незащищённый Wi-Fi доступен для атак
- Устаревшие протоколы (WEP) легко взламываются
- Злоумышленники могут перехватывать трафик

📋 НОРМАТИВНОЕ ТРЕБОВАНИЕ (Приказ ФСТЭК №21 п. II, мера 14):
Беспроводные соединения должны быть защищены (WPA2/WPA3, корпоративная аутентификация).

🛠️ КАК НАСТРОИТЬ:

1. Отключите Wi-Fi, если не нужен:
   - Панель управления → Сетевые подключения
   - Отключите беспроводной адаптер

2. Если Wi-Fi нужен, настройте безопасность:
   - Используйте WPA2 или WPA3
   - Установите сложный пароль (минимум 12 символов)
   - Включите корпоративную аутентификацию (802.1X)

3. Скрывайте SSID сети

📊 ДОПОЛНИТЕЛЬНЫЕ РЕКОМЕНДАЦИИ:
- Отключите WPS (Wi-Fi Protected Setup)
- Регулярно меняйте пароль Wi-Fi
- Ведите список подключённых устройств
"""
    
    def check(self) -> dict:
        try:
            result = subprocess.run(
                ['netsh', 'wlan', 'show', 'interfaces'],
                capture_output=True, text=True, encoding='cp866', errors='replace'
            )
            if 'Нет беспроводного интерфейса' in result.stdout or 'There is no wireless interface' in result.stdout:
                return self._get_result(True, "Wi-Fi отключён", "✅ Беспроводные интерфейсы не обнаружены")
            else:
                if 'WPA2' in result.stdout or 'WPA3' in result.stdout:
                    return self._get_result(True, "Wi-Fi с WPA2/WPA3", "✅ Беспроводная сеть защищена")
                elif 'WEP' in result.stdout:
                    return self._get_result(False, "Wi-Fi с WEP", "❌ Используется устаревший стандарт WEP. Настройте WPA2/WPA3")
                else:
                    return self._get_result(False, "Незащищённый Wi-Fi", "⚠️ Wi-Fi может быть без защиты. Проверьте настройки роутера")
        except:
            return self._get_result(True, "OK", "✅ Не удалось проверить беспроводные сети")


