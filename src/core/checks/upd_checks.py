# УПД.6 — ОГРАНИЧЕНИЕ НЕУСПЕШНЫХ ПОПЫТОК ВХОДА
# ============================================================================

class UPD6Checker(BaseChecker):
    def __init__(self):
        super().__init__("УПД.6", "Ограничение неуспешных попыток входа", "critical", is_manual=False)
        self.required_levels = [1, 2, 3, 4]
        self.detailed_description = r"""
📌 ЧТО ПРОВЕРЯЕТСЯ:
Проверяется настройка блокировки учётной записи после нескольких неудачных попыток входа.

✅ ПОЧЕМУ ЭТО ВАЖНО:
- Защита от атак подбора пароля (brute force)
- Злоумышленник не сможет бесконечно перебирать пароли
- Автоматическая блокировка сигнализирует о попытке взлома

📋 НОРМАТИВНОЕ ТРЕБОВАНИЕ (Приказ ФСТЭК №21 п. II, мера 6):
Должно быть реализовано ограничение количества неуспешных попыток входа (не более 5) с блокировкой на установленное время.

🛠️ КАК НАСТРОИТЬ:

Способ 1: Локальная групповая политика (gpedit.msc)
1. Нажмите Win+R, введите gpedit.msc
2. Перейдите: Конфигурация компьютера → Windows → Параметры безопасности → Политика учётных записей → Политика блокировки
3. Настройте:
   - Пороговое значение блокировки: 5 попыток
   - Длительность блокировки: 30 минут
   - Сброс счётчика блокировки: 30 минут

Способ 2: PowerShell (от администратора)
net accounts /lockoutthreshold:5
net accounts /lockoutduration:30
net accounts /lockoutwindow:30

📊 ДОПОЛНИТЕЛЬНЫЕ РЕКОМЕНДАЦИИ:
- Настройте уведомления о блокировке учётных записей
- Ведите журнал неудачных попыток входа
- Для критических систем — блокировка до ручного разблокирования
"""
    
    def check(self) -> dict:
        try:
            result = subprocess.run(['net', 'accounts'], capture_output=True, text=True, encoding='cp866', errors='replace')
            threshold = None
            duration = None
            for line in result.stdout.split('\n'):
                if 'пороговое значение блокировки' in line.lower() or 'lockout threshold' in line.lower():
                    nums = re.findall(r'\d+', line)
                    if nums:
                        threshold = int(nums[0])
                if 'длительность блокировки' in line.lower() or 'lockout duration' in line.lower():
                    nums = re.findall(r'\d+', line)
                    if nums:
                        duration = int(nums[0])
            if threshold and threshold <= 5 and duration and duration > 0:
                return self._get_result(True, f"Порог: {threshold}, Длительность: {duration} мин", 
                    f"✅ Блокировка после {threshold} попыток на {duration} минут")
            elif threshold:
                return self._get_result(False, f"Порог: {threshold}", 
                    f"⚠️ Блокировка после {threshold} попыток, но не настроена длительность")
            else:
                return self._get_result(False, "Не настроена", 
                    "❌ Блокировка при неудачных попытках не настроена. Настройте политику блокировки через gpedit.msc")
        except Exception as e:
            return self._get_result(False, str(e), f"❌ Ошибка проверки: {e}")


