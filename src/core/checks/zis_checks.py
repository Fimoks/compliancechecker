# ЗИС.3 — ЗАЩИТА ПРИ ПЕРЕДАЧЕ ПО КАНАЛАМ СВЯЗИ
# ============================================================================

class ZIS3Checker(BaseChecker):
    def __init__(self):
        super().__init__("ЗИС.3", "Защита при передаче по каналам связи", "critical", is_manual=False)
        self.required_levels = [1, 2, 3, 4]
        self.detailed_description = r"""
📌 ЧТО ПРОВЕРЯЕТСЯ:
Проверяется, включена ли поддержка TLS 1.2/1.3 и отключены ли устаревшие протоколы SSL 2.0/3.0.

✅ ПОЧЕМУ ЭТО ВАЖНО:
- SSL и TLS 1.0 содержат критические уязвимости (POODLE, BEAST)
- Злоумышленник может перехватить и расшифровать трафик
- Обязательное требование для всех уровней защищённости

📋 НОРМАТИВНОЕ ТРЕБОВАНИЕ (Приказ ФСТЭК №21 п. XIII, мера 3):
Должна обеспечиваться защита информации при её передаче по сетям связи.

🛠️ КАК НАСТРОИТЬ:

Способ 1: Через реестр Windows
1. Нажмите Win+R, введите regedit
2. Перейдите к: HKEY_LOCAL_MACHINE\SYSTEM\CurrentControlSet\Control\SecurityProviders\SCHANNEL\Protocols
3. Для каждого устаревшего протокола создайте разделы и параметры:
   - SSL 2.0: Enabled = 0
   - SSL 3.0: Enabled = 0
   - TLS 1.0: Enabled = 0 (опционально)
4. Включите TLS 1.2: Enabled = 1

Способ 2: Специализированные утилиты
- IIS Crypto (рекомендуется)
- Nartac IIS Crypto

📊 ДОПОЛНИТЕЛЬНЫЕ РЕКОМЕНДАЦИИ:
- Используйте только TLS 1.2 и выше
- Отключите слабые шифры (RC4, DES, 3DES)
- Регулярно проверяйте настройки SSL/TLS
"""
    
    def check(self) -> dict:
        if is_tls_enabled():
            return self._get_result(True, "TLS включён", "✅ Передача данных защищена (TLS 1.2/1.3 активен).")
        else:
            return self._get_result(False, "TLS не настроен", "❌ Обнаружены устаревшие протоколы SSL. Настройте TLS 1.2/1.3 через IIS Crypto или реестр.")


