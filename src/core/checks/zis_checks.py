# ЗИС.11 — ОБЕСПЕЧЕНИЕ ПОДЛИННОСТИ СЕТЕВЫХ СОЕДИНЕНИЙ
# ============================================================================

class ZIS11Checker(BaseChecker):
    def __init__(self):
        super().__init__("ЗИС.11", "Подлинность сетевых соединений", "high", is_manual=False)
        self.required_levels = [1, 2]
        self.detailed_description = r"""
📌 ЧТО ПРОВЕРЯЕТСЯ:
Проверяется, настроено ли шифрование для RDP-подключений (TLS).

✅ ПОЧЕМУ ЭТО ВАЖНО:
- RDP без шифрования позволяет перехватывать данные сессии
- Злоумышленник может украсть пароли и конфиденциальные данные
- Обязательное требование для УЗ-1 и УЗ-2

📋 НОРМАТИВНОЕ ТРЕБОВАНИЕ (Приказ ФСТЭК №21 п. XIII, мера 11):
Должно обеспечиваться обеспечение подлинности сетевых соединений.

🛠️ КАК НАСТРОИТЬ:

1. Откройте gpedit.msc
2. Перейдите: Конфигурация компьютера → Административные шаблоны → Компоненты Windows → Службы удалённых рабочих столов → Узел сеансов удалённых рабочих столов → Безопасность
3. Установите 'Требовать использования специального уровня безопасности' = 'Включён'
4. В 'Уровень безопасности' выберите 'TLS 1.0' (или выше)

ИЛИ через реестр:
HKLM\SYSTEM\CurrentControlSet\Control\Terminal Server\WinStations\RDP-Tcp
SecurityLayer = 2 (TLS)

📊 ДОПОЛНИТЕЛЬНЫЕ РЕКОМЕНДАЦИИ:
- Используйте VPN для удалённого доступа
- Ограничьте список пользователей RDP
- Измените стандартный порт 3389
"""
    
    def check(self) -> dict:
        if is_rdp_secured():
            return self._get_result(True, "RDP защищён (TLS)", "✅ Подлинность RDP-соединений обеспечена (шифрование TLS).")
        else:
            return self._get_result(False, "RDP без TLS", "⚠️ RDP использует небезопасное шифрование. Настройте TLS через групповые политики.")


