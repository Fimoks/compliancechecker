# ЗНИ.2 — УПРАВЛЕНИЕ ДОСТУПОМ К МАШИННЫМ НОСИТЕЛЯМ
# ============================================================================

class ZNI2Checker(BaseChecker):
    def __init__(self):
        super().__init__("ЗНИ.2", "Управление доступом к машинным носителям", "high", is_manual=False)
        self.required_levels = [1, 2]
        self.detailed_description = r"""
📌 ЧТО ПРОВЕРЯЕТСЯ:
Проверяется, запрещена ли запись на съёмные USB-накопители через групповые политики Windows.

✅ ПОЧЕМУ ЭТО ВАЖНО:
- Предотвращает несанкционированный вынос данных на USB-накопителях
- Защищает от утечек конфиденциальной информации
- Является обязательным требованием для УЗ-1 и УЗ-2

📋 НОРМАТИВНОЕ ТРЕБОВАНИЕ (Приказ ФСТЭК №21 п. IV, мера 2):
Подключение съёмных носителей должно контролироваться и ограничиваться (запрет записи, контроль портов).

🛠️ КАК НАСТРОИТЬ:

Способ 1: Локальная групповая политика (gpedit.msc)
1. Нажмите Win+R, введите gpedit.msc
2. Перейдите: Конфигурация компьютера → Административные шаблоны → Система → Доступ к съёмным запоминающим устройствам
3. Включите политику:
   - "Съёмные диски: запретить чтение" (для полного запрета)
   - ИЛИ "Съёмные диски: запретить запись" (только запрет записи)
4. Нажмите "ОК" и перезагрузите компьютер

Способ 2: Реестр Windows
1. Нажмите Win+R, введите regedit
2. Перейдите к: HKEY_LOCAL_MACHINE\SOFTWARE\Policies\Microsoft\Windows\RemovableStorageDevices
3. Создайте раздел с GUID: {53f5630d-b6bf-11d0-94f2-00a0c91efb8b}
4. Создайте параметр DWORD "Deny_Write" со значением 1

Способ 3: PowerShell (от администратора)
# Запрет записи на USB
$keyPath = "HKLM:\SOFTWARE\Policies\Microsoft\Windows\RemovableStorageDevices\{53f5630d-b6bf-11d0-94f2-00a0c91efb8b}"
New-Item -Path $keyPath -Force
Set-ItemProperty -Path $keyPath -Name "Deny_Write" -Value 1 -Type DWord

📊 ДОПОЛНИТЕЛЬНЫЕ РЕКОМЕНДАЦИИ:
- Для УЗ-1 и УЗ-2 запрет записи на USB обязателен
- Ведите журнал подключения USB-устройств
- Используйте шифрование для разрешённых USB-накопителей
- Рассмотрите внедрение DLP-системы для контроля данных
"""
    
    def check(self) -> dict:
        if is_usb_write_protected():
            return self._get_result(
                True,
                "Запись на USB запрещена",
                "✅ Доступ к съёмным носителям ограничен (запрет записи). Соответствует требованиям."
            )
        else:
            return self._get_result(
                False,
                "Запись на USB разрешена",
                "❌ Запись на USB разрешена. Настройте политику запрета записи через gpedit.msc → Административные шаблоны → Система → Доступ к съёмным запоминающим устройствам."
            )


