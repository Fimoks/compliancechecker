# ============================================================================
# ЗТС.3 — КОНТРОЛЬ ФИЗИЧЕСКОГО ДОСТУПА К ТЕХНИЧЕСКИМ СРЕДСТВАМ
# ============================================================================

class ZTS3ManualChecker(BaseChecker):
    def __init__(self):
        super().__init__("ЗТС.3", "Контроль физического доступа к техническим средствам", "high", is_manual=True)
        self.required_levels = [1, 2, 3, 4]
        self.question = ("Осуществляется ли контроль физического доступа в помещения, где установлены технические средства, "
                         "обрабатывающие персональные данные (пропускная система, охрана, видеонаблюдение)?")
        self.detailed_description = r"""
📌 ЧТО ПРОВЕРЯЕТСЯ:
Ручная проверка — наличие системы контроля физического доступа в помещения с оборудованием.

✅ ПОЧЕМУ ЭТО ВАЖНО:
- Физический доступ к компьютеру даёт возможность обойти любые программные защиты
- Злоумышленник может скопировать данные, установить шпионское ПО, похитить носители
- Является базовым требованием для всех уровней защищённости

📋 НОРМАТИВНОЕ ТРЕБОВАНИЕ (Приказ ФСТЭК №21 п. XII, мера 3):
Должен контролироваться физический доступ к техническим средствам.

🛠️ КАК ОРГАНИЗОВАТЬ:

Для серверных/сетевых стоек (критическое оборудование):
1. Установите систему контроля доступа (СКУД):
   - Электронные замки с картами доступа
   - Биометрическая аутентификация (отпечатки пальцев)
2. Ведите журнал посещений серверной
3. Назначьте ответственных за доступ

Для рабочих мест сотрудников:
1. Ограничьте доступ посторонних в офис (ресепшн, пропуска)
2. Используйте замки на дверях кабинетов
3. Ведите журнал посетителей

Общие рекомендации:
- Установите видеонаблюдение в зонах с оборудованием
- Ограничьте возможность подключения к компьютерам посторонних устройств
- Контролируйте вынос оборудования с территории

📊 ДОПОЛНИТЕЛЬНЫЕ РЕКОМЕНДАЦИИ:
- Для УЗ-1 и УЗ-2 — обязательна СКУД и видеонаблюдение
- Проводите инструктаж сотрудников о правилах физической безопасности
- Периодически проверяйте журналы доступа
"""
    
    def check(self) -> dict:
        return self._get_result(False, None, self.question)


# ============================================================================
# ЗТС.4 — РАЗМЕЩЕНИЕ УСТРОЙСТВ ВЫВОДА ИНФОРМАЦИИ
# ============================================================================

class ZTS4ManualChecker(BaseChecker):
    def __init__(self):
        super().__init__("ЗТС.4", "Размещение устройств вывода информации", "medium", is_manual=True)
        self.required_levels = [1, 2, 3, 4]
        self.question = ("Размещены ли устройства вывода информации (мониторы, проекторы) таким образом, "
                         "чтобы исключить несанкционированный просмотр персональных данных посторонними лицами?")
        self.detailed_description = r"""
📌 ЧТО ПРОВЕРЯЕТСЯ:
Ручная проверка — правильность размещения экранов мониторов и других устройств вывода.

✅ ПОЧЕМУ ЭТО ВАЖНО:
- Личная информация может быть увидена посторонними (подсматривание)
- Особенно критично на ресепшн, в открытых офисах, у окон
- Защита от визуального перехвата информации

📋 НОРМАТИВНОЕ ТРЕБОВАНИЕ (Приказ ФСТЭК №21 п. XII, мера 4):
Устройства вывода информации должны быть размещены исключая несанкционированный просмотр.

🛠️ КАК ОРГАНИЗОВАТЬ:

Основные принципы размещения:
1. Мониторы должны стоять спиной к:
   - Окнам
   - Дверям
   - Проходам
   - Местам общего пользования

2. Для открытых пространств:
   - Используйте защитные экраны (приватность-фильтры)
   - Устанавливайте мониторы так, чтобы экран был виден только пользователю

3. Дополнительные меры:
   - Настройте автоматическую блокировку экрана (5-15 минут бездействия)
   - Используйте программное затемнение неактивных окон
   - Переворачивайте экран в сторону стены при уходе с рабочего места

4. Для принтеров и МФУ:
   - Размещайте в недоступных для посторонних местах
   - Настройте вывод на печать только после ввода пин-кода
   - Сразу забирайте распечатанные документы

📊 ДОПОЛНИТЕЛЬНЫЕ РЕКОМЕНДАЦИИ:
- Проводите инструктаж о необходимости блокировки экрана при уходе
- Для УЗ-1 используйте защитные экраны на всех мониторах
- Периодически проверяйте, не изменилась ли обстановка (перестановка мебели)
"""
    
    def check(self) -> dict:
        return self._get_result(False, None, self.question)


